-- 2) Public, count-only view of approved supplier applications for the
--    homepage progress counter. Returns a single integer; exposes no rows.
create or replace function public.joined_supplier_count()
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select count(*)::int from public.supplier_applications where status = 'approved';
$$;
revoke all on function public.joined_supplier_count() from public;
grant execute on function public.joined_supplier_count() to anon, authenticated;
