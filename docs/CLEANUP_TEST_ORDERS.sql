-- الخطوة ١ — اقرأ قبل أن تحذف. تأكّد أن هذه هي الأربعة فعلاً:
select order_number, created_at, status, left(customer_notes, 80) as notes
from public.orders
where order_number in (
  'BENA-2026-00005','BENA-2026-00006','BENA-2026-00007','BENA-2026-00008'
)
order by order_number;

-- الخطوة ٢ — احذف البنود المرتبطة أولاً (مفتاح خارجي):
delete from public.order_items
where order_id in (
  select id from public.orders
  where order_number in (
    'BENA-2026-00005','BENA-2026-00006','BENA-2026-00007','BENA-2026-00008'
  )
);

-- الخطوة ٣ — ثم احذف الطلبات نفسها:
delete from public.orders
where order_number in (
  'BENA-2026-00005','BENA-2026-00006','BENA-2026-00007','BENA-2026-00008'
);

-- الخطوة ٤ — تحقّق. يجب أن تعود صفراً:
select count(*) as remaining_test_orders
from public.orders
where order_number like 'BENA-%';


